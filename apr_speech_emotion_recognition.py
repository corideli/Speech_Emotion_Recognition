"""## 8. Unsupervised Exploration: PCA and k-means

**Principal Component Analysis (PCA)** is applied to the development features after imputation and standardization. PCA combines the original features into new variables called principal components. These describe mutually orthogonal directions and are ordered from highest to lowest explained variance, allowing the data to be represented in fewer dimensions. The number of components is chosen to retain at least **95% of the variance**; the first two are used for two-dimensional visualization.

**k-means** is applied to the transformed space with **k = 4**, equal to the number of emotions considered, without supplying the labels to the algorithm. The quality of the resulting structure is described by the **silhouette score**; its correspondence with the true emotions is assessed using the **Adjusted Rand Index (ARI)**, **Normalized Mutual Information (NMI)**, and a contingency table.

In the run analyzed, retaining **95% of the variance requires 52 components**. The silhouette score is **0.107**, ARI is **0.105**, and NMI is **0.133**: the cluster structure is poorly separated and only weakly aligned with the emotion labels. Unsupervised separation does not necessarily match the separation achievable by a classifier trained with labels.
"""

