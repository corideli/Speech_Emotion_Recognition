"""## 6. Acoustic Feature Extraction

Each recording is converted to mono, resampled to **16 kHz** when necessary, and centered by subtracting the direct-current component (*DC offset*). The signal is divided into overlapping frames and analyzed using the **Short-Time Fourier Transform (STFT)** with a Hann window. A Mel-band representation is obtained from the power spectrum, converted to a logarithmic scale (**Log-Mel spectrogram**), and used to calculate the **MFCCs**.

The vector includes the **13 MFCCs**, their first (**delta**) and second (**delta-delta**) temporal derivatives, as well as measures of energy, zero crossings, spectral distribution, and periodicity. It includes **RMS**, **ZCR**, *spectral centroid*, *bandwidth*, *rolloff*, *flatness*, *entropy*, *flux*, and estimates of fundamental frequency (**pitch**) based on autocorrelation.

Because the recordings have different durations, time-varying features are summarized mainly by their **mean and standard deviation**. This yields **101 features per recording**: 78 related to MFCCs/delta/delta-delta, 16 to energy and spectral properties, and 7 to pitch and periodicity. This aggregation produces fixed-length vectors compatible with SVM and Random Forest, at the cost of losing part of the temporal ordering of speech information.

The procedure does not remove silences or normalize signal amplitude; consequently, energy level and pauses remain potentially informative but are also sensitive to changes in acoustic conditions. The final matrices contain **575 × 101** features for development and **192 × 101** for testing. Any missing values are handled later within the learning pipelines.
"""

MEL_FILTER=librosa.filters.mel(sr=SR,n_fft=N_FFT,n_mels=N_MELS,fmin=0,fmax=SR/2)
FREQS=librosa.fft_frequencies(sr=SR,n_fft=N_FFT)[:,None]
WINDOW=signal.windows.hann(N_FFT,sym=False)[:,None]
def load_audio(path):
    y,sr=sf.read(path,dtype='float64',always_2d=True)
    y=y.mean(axis=1)
    if sr!=SR: y=librosa.resample(y,orig_sr=sr,target_sr=SR,res_type='soxr_hq')
    if not np.isfinite(y).all() or len(y)<N_FFT or np.max(np.abs(y))<1e-10:
        raise ValueError(f'Invalid audio: {path}')
    return y-y.mean()  # DC removal, same procedure for all signals

def representations(y):
    frames=librosa.util.frame(y,frame_length=N_FFT,hop_length=HOP)
    mag=np.abs(np.fft.rfft(frames*WINDOW,axis=0))
    power=mag**2
    logmel=librosa.power_to_db(MEL_FILTER@power,ref=1.0,top_db=80)
    return frames,mag,power,logmel

def extract_features(y):
    frames,mag,power,logmel=representations(y)
    mfcc=librosa.feature.mfcc(S=logmel,n_mfcc=N_MFCC)
    feats={}
    def stats(prefix,values):
        values=np.asarray(values)
        feats[prefix+'_mean']=float(np.mean(values))
        feats[prefix+'_std']=float(np.std(values))
    for prefix,arr in [('mfcc',mfcc),('delta',librosa.feature.delta(mfcc,mode='nearest')),
                       ('delta2',librosa.feature.delta(mfcc,order=2,mode='nearest'))]:
        for i,row in enumerate(arr): stats(f'{prefix}_{i:02d}',row)
    eps=1e-12
    rms=np.sqrt(np.mean(frames**2,axis=0))
    spectral_prob=power/(power.sum(axis=0,keepdims=True)+eps)
    norm_mag=mag/(mag.sum(axis=0,keepdims=True)+eps)
    centroid=(FREQS*norm_mag).sum(axis=0)
    bandwidth=np.sqrt((((FREQS-centroid)**2)*norm_mag).sum(axis=0))
    rolloff=FREQS[np.argmax(np.cumsum(power,axis=0)>=0.85*power.sum(axis=0),axis=0),0]
    flatness=np.exp(np.log(power+eps).mean(axis=0))/(power.mean(axis=0)+eps)
    entropy=-(spectral_prob*np.log(spectral_prob+eps)).sum(axis=0)/np.log(power.shape[0])
    flux=np.r_[0.,np.sqrt(np.sum(np.diff(norm_mag,axis=1)**2,axis=0))]
    for name,arr in dict(rms=rms,zcr=np.mean(np.diff(np.signbit(frames),axis=0),axis=0),
            centroid=centroid,bandwidth=bandwidth,rolloff=rolloff,flatness=flatness,
            entropy=entropy,flux=flux).items(): stats(name,arr)
    centered=frames-frames.mean(axis=0,keepdims=True)
    spectrum=np.fft.rfft(centered*WINDOW,n=2*N_FFT,axis=0)
    ac=np.fft.irfft(spectrum*np.conj(spectrum),n=2*N_FFT,axis=0)[:N_FFT].real
    ac=ac/(ac[0:1]+eps)
    lo,hi=int(np.ceil(SR/500)),int(np.floor(SR/65))
    lags=np.argmax(ac[lo:hi+1],axis=0)+lo
    periodicity=ac[lags,np.arange(ac.shape[1])]
    voiced=(periodicity>=0.3)&(rms>=max(float(rms.max())*0.1,1e-8))
    f0=SR/lags[voiced]
    feats['pitch_mean']=float(f0.mean()) if len(f0) else np.nan
    feats['pitch_std']=float(f0.std()) if len(f0) else np.nan
    feats['pitch_median']=float(np.median(f0)) if len(f0) else np.nan
    feats['pitch_p90_p10']=float(np.percentile(f0,90)-np.percentile(f0,10)) if len(f0) else np.nan
    feats['voiced_fraction']=float(voiced.mean())
    stats('periodicity',periodicity)
    return feats

